// Generates Sprawl's icon set from Lucide (ISC). Sprawl's names are its own; each maps to one Lucide icon.
//   npm pack lucide-static@1.69.0 && tar -xzf lucide-static-1.69.0.tgz
//   node scripts/generate-icons.mjs <path to the unpacked package/>
// Writes the web drawings, the server drawings, the vocabulary and the MCP enum. Commit what it writes.
import { readFileSync, writeFileSync } from 'node:fs';
import { join } from 'node:path';

const VERSION = '1.69.0';
const ICONS = {
  user: 'user', users: 'users', server: 'server', database: 'database', cache: 'database-zap', cloud: 'cloud', 'cloud-service': 'cloud-cog',
  globe: 'globe', phone: 'smartphone', laptop: 'laptop', monitor: 'monitor', lock: 'lock', key: 'key-round', shield: 'shield', mail: 'mail',
  message: 'message-square', bell: 'bell', search: 'search', cpu: 'cpu', memory: 'memory-stick', disk: 'hard-drive', folder: 'folder',
  file: 'file-text', code: 'code', terminal: 'terminal', git: 'git-branch', package: 'package', container: 'container', box: 'box',
  layers: 'layers', network: 'network', router: 'router', wifi: 'wifi', api: 'plug', webhook: 'webhook', function: 'square-function',
  workflow: 'workflow', settings: 'settings', clock: 'clock', calendar: 'calendar', 'bar-chart': 'chart-column', 'line-chart': 'chart-line',
  gauge: 'gauge', payment: 'credit-card', cart: 'shopping-cart', bot: 'bot', brain: 'brain', bolt: 'zap', queue: 'inbox', list: 'list',
  'load-balancer': 'split', warning: 'triangle-exclamation-point', ok: 'circle-check', error: 'circle-x', book: 'book-open', image: 'image',
  map: 'map', home: 'house', building: 'building', money: 'circle-dollar-sign', eye: 'eye', flag: 'flag', idea: 'lightbulb', rocket: 'rocket',
  tool: 'wrench', upload: 'upload', download: 'download', sync: 'refresh-cw', filter: 'funnel', sparkles: 'sparkles',
};

const pkg = process.argv[2];
if (!pkg) throw new Error('Pass the path to the unpacked lucide-static package.');
const version = JSON.parse(readFileSync(join(pkg, 'package.json'), 'utf8')).version;
if (version !== VERSION) throw new Error(`Expected lucide-static ${VERSION}, found ${version}.`);
const nodes = JSON.parse(readFileSync(join(pkg, 'icon-nodes.json'), 'utf8'));
const license = readFileSync(join(pkg, 'LICENSE'), 'utf8').trim();
const names = Object.keys(ICONS);
for (const [name, lucide] of Object.entries(ICONS)) if (!nodes[lucide]) throw new Error(`Lucide has no icon '${lucide}' (for '${name}').`);

const notice = (prefix) => [`Generated by scripts/generate-icons.mjs from lucide-static ${VERSION}. Do not edit.`, '', ...license.split('\n')]
  .map((line) => `${prefix}${line}`.trimEnd()).join('\n');
const escapeXml = (value) => value.replace(/&/g, '&amp;').replace(/"/g, '&quot;').replace(/</g, '&lt;');
const markup = (lucide) => nodes[lucide].map(([tag, attrs]) => `<${tag} ${Object.entries(attrs).map(([k, v]) => `${k}="${escapeXml(v)}"`).join(' ')}/>`).join('');
const pascal = (name) => name.split('-').map((p) => p[0].toUpperCase() + p.slice(1)).join('');
const cs = (value) => value.replace(/\\/g, '\\\\').replace(/"/g, '\\"');

writeFileSync('src/Sprawl.Web/src/canvas/icons.ts', `${notice('// ')}

/** Icons a shape or card can carry, drawn in a 24 × 24 box with a 2 px round stroke in the current colour. */
export const ICON_NAMES = ${JSON.stringify(names)} as const;
export type IconName = (typeof ICON_NAMES)[number];

type IconNode = readonly [tag: string, attributes: Readonly<Record<string, string>>];
export const ICON_NODES: Readonly<Record<IconName, readonly IconNode[]>> = {
${names.map((n) => `  ${JSON.stringify(n)}: ${JSON.stringify(nodes[ICONS[n]])},`).join('\n')}
};
`);

writeFileSync('src/Sprawl.Contracts/Icons.g.cs', `${notice('// ')}

namespace Sprawl.Contracts;

/// <summary>The icons a shape or card can carry (drawn from Lucide). Names are Sprawl's own.</summary>
public static class Icons
{
    public static readonly string[] All = [${names.map((n) => `"${n}"`).join(', ')}];
}
`);

writeFileSync('src/Sprawl.Domain/IconPaths.g.cs', `${notice('// ')}

namespace Sprawl.Domain;

/// <summary>Each icon's SVG elements for a 24 × 24 box (fill none, stroke currentColor, width 2, round caps and joins).</summary>
public static class IconPaths
{
    public static readonly IReadOnlyDictionary<string, string> Markup = new Dictionary<string, string>(StringComparer.Ordinal)
    {
${names.map((n) => `        ["${n}"] = "${cs(markup(ICONS[n]))}",`).join('\n')}
    };
}
`);

writeFileSync('src/Sprawl.Mcp/Tools/IconName.g.cs', `${notice('// ')}

using System.Text.Json.Serialization;

namespace Sprawl.Mcp.Tools;

[JsonConverter(typeof(JsonStringEnumConverter<IconName>))]
public enum IconName
{
    [JsonStringEnumMemberName("none")] None,
${names.map((n) => `    [JsonStringEnumMemberName("${n}")] ${pascal(n)},`).join('\n')}
}
`);
console.log(`${names.length} icons written.`);
